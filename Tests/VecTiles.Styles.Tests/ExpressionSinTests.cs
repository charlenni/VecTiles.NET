using System.Text.Json.Nodes;
using VecTiles.Styles.MapLibre.Expressions;

namespace VecTiles.Styles.MapboxTests;

/// <summary>
/// Tests based on the MapLibre Native expression equality fixtures
/// sin.a:
/// ["sin", 0]
/// sin.b: differs in the angle.
/// </summary>
public class ExpressionSinTests
{
    /// <summary>
    /// Verifies that fixture a is structurally equal to a second parse of the same fixture.
    /// </summary>
    [Fact]
    public void FixtureIsStructurallyEqualToItselfTest()
    {
        var expressionA1 = ExpressionFixture.Parse("sin", "a");
        var expressionA2 = ExpressionFixture.Parse("sin", "a");

        Assert.NotNull(expressionA1);
        Assert.NotNull(expressionA2);
        Assert.Equal(expressionA1, expressionA2);
    }

    /// <summary>
    /// Verifies that fixture a is not structurally equal to fixture b, which differs in exactly one leaf.
    /// </summary>
    [Fact]
    public void FixtureIsUnequalToOtherFixtureTest()
    {
        var expressionA = ExpressionFixture.Parse("sin", "a");
        var expressionB = ExpressionFixture.Parse("sin", "b");

        Assert.NotNull(expressionA);
        Assert.NotNull(expressionB);
        Assert.NotEqual(expressionA, expressionB);
    }

    /// <summary>
    /// Verifies that the fixtures evaluate to the expected results.
    /// </summary>
    [Fact]
    public void FixtureEvaluationTest()
    {
        Assert.Equal(0d, ExpressionFixture.Parse("sin", "a")!.Evaluate(ExpressionTestsHelper.CreateContext()));
        Assert.Equal(0.8414709848078965, ExpressionFixture.Parse("sin", "b")!.Evaluate(ExpressionTestsHelper.CreateContext()));
    }
}
