namespace VecTiles.Styles.Mapsforge.Enums;

/// <summary>
/// Text transformation applied to caption and pathText texts (Mapsforge
/// attribute "text-transform").
/// </summary>
public enum MapsforgeTextTransform
{
    /// <summary>No transformation.</summary>
    None,
    /// <summary>Uppercase text.</summary>
    Uppercase,
    /// <summary>Lowercase text.</summary>
    Lowercase,
    /// <summary>Capitalize the first character of words.</summary>
    Capitalize
}
